import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const entry = resolve(root, 'web/node_modules/chess.js/dist/esm/chess.js')
const output = resolve(root, 'app/src/main/assets/analysis/chess-rules.js')

await mkdir(dirname(output), { recursive: true })
await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  globalName: 'InstinctaZeroChessRules',
  target: ['es2017'],
  legalComments: 'inline',
  banner: {
    js: '/* Generated by web/build-chess-rules.mjs from chess.js 1.4.0; BSD-2-Clause. */'
  },
  outfile: output
})

const source = await readFile(output, 'utf8')
const sandbox = {}
vm.runInNewContext(source, sandbox, { filename: output })
const { Chess } = sandbox.InstinctaZeroChessRules

// Exercise the generated browser bundle itself, including the special moves the
// local study controller relies on. These assertions deliberately avoid any UI.
const initial = new Chess()
assert.equal(initial.moves().length, 20)
assert.equal(initial.move({ from: 'e2', to: 'e4' }).san, 'e4')

const castle = new Chess('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1')
assert.equal(castle.move({ from: 'e1', to: 'g1' }).san, 'O-O')
assert.equal(castle.get('g1').type, 'k')
assert.equal(castle.get('f1').type, 'r')

const enPassant = new Chess('4k3/8/8/3pP3/8/8/8/4K3 w - d6 0 1')
assert.equal(enPassant.move({ from: 'e5', to: 'd6' }).san, 'exd6')
assert.equal(enPassant.get('d5'), undefined)

const promotion = new Chess('7k/P7/8/8/8/8/8/7K w - - 0 1')
assert.equal(promotion.move({ from: 'a7', to: 'a8', promotion: 'q' }).san, 'a8=Q+')
assert.equal(promotion.get('a8').type, 'q')

const bytes = Buffer.from(source)
console.log(`${output}: ${bytes.length} bytes sha256=${createHash('sha256').update(bytes).digest('hex')}; browser-bundle legal-move checks passed`)
