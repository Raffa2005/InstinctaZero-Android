import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { mkdir, readFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const entry = resolve(root, 'web-src/legacy-chessground/entry.ts')
const output = resolve(root, 'app/src/main/assets/analysis/legacy-chessground.js')

await mkdir(dirname(output), { recursive: true })
await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  globalName: 'InstinctaZeroLegacyChessground',
  target: ['es2017'],
  legalComments: 'inline',
  banner: {
    js: '/* Generated by web/build-legacy-chessground.mjs from lichobile 063167dda7119386cf36708d004d4565203d449a; GPL-3.0-or-later. */'
  },
  outfile: output
})

const bytes = await readFile(output)
console.log(`${output}: ${bytes.length} bytes sha256=${createHash('sha256').update(bytes).digest('hex')}`)
