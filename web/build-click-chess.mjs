import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {build} from 'esbuild';
const root = new URL('../', import.meta.url);
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(sha(await readFile(new URL('web-src/click-chess/origin-ranker.bin', root))), '592efffc0cef663b7b8041669fe4332322fb5e41b13990893f8d36046c256839');
assert.equal(sha(await readFile(new URL('web-src/click-chess/ranker.mjs', root))), '3957ad0ab1fcb44ce6544a354c14c552b3d0bf5a216d2529e95e41dc7ca5a909');
const output = new URL('app/src/main/assets/analysis/click-chess.js', root);
const result = await build({entryPoints:[new URL('web-src/click-chess/entry.mjs',root).pathname], bundle:true, minify:true, format:'iife', globalName:'InstinctaClickChess', target:['es2017'], loader:{'.bin':'binary'}, write:false,
  banner:{js:'/* Generated by web/build-click-chess.mjs. click-chess runtime/model: MIT; see click-chess-LICENSE.txt. App input adapter: GPL-3.0-or-later. */'}});
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) assert.deepEqual(await readFile(output), Buffer.from(bytes), 'Run npm run build:click-chess and commit the generated asset');
else await writeFile(output, bytes);
console.log(`click-chess.js: ${bytes.length} bytes, sha256=${sha(bytes)}; pinned model/runtime verified`);
